import { NextRequest, NextResponse } from "next/server";
import { isOwnerAuthenticated, verifyOwnerPassword, setOwnerPassword } from "@/lib/auth";

export async function POST(req: NextRequest) {
  try {
    const isAuth = await isOwnerAuthenticated();
    if (!isAuth) {
      return NextResponse.json(
        { success: false, message: "Unauthorized" },
        { status: 401 }
      );
    }

    const { currentPassword, newPassword } = await req.json();

    if (!currentPassword || !newPassword) {
      return NextResponse.json(
        { success: false, message: "Current and new password are required" },
        { status: 400 }
      );
    }

    if (newPassword.length < 6) {
      return NextResponse.json(
        { success: false, message: "New password must be at least 6 characters" },
        { status: 400 }
      );
    }

    const isCurrentValid = await verifyOwnerPassword(currentPassword);
    if (!isCurrentValid) {
      return NextResponse.json(
        { success: false, message: "Current password does not match" },
        { status: 400 }
      );
    }

    const updated = await setOwnerPassword(newPassword);
    if (!updated) {
      return NextResponse.json(
        { success: false, message: "Failed to update password" },
        { status: 500 }
      );
    }

    return NextResponse.json({
      success: true,
      message: "Password updated successfully",
    });
  } catch (error) {
    console.error("Change password error:", error);
    return NextResponse.json(
      { success: false, message: "Internal server error" },
      { status: 500 }
    );
  }
}
